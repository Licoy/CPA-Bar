ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.environ.get("ICON_CACHE", os.path.join(tempfile.gettempdir(), "cpabar-icons"))


def package(name, version):
    """Returns the directory of an npm package, downloading it once."""
    dest = os.path.join(CACHE, name.replace("/", "_").replace("@", "") + "-" + version)
    if not os.path.isdir(dest):
        base = name.split("/")[-1]
        url = f"https://registry.npmjs.org/{name}/-/{base}-{version}.tgz"
        with urllib.request.urlopen(url, timeout=300) as r:
            data = r.read()
        with tarfile.open(fileobj=io.BytesIO(data)) as tar:
            tar.extractall(dest, filter="data")
    return os.path.join(dest, "package")


def remix_body(path):
    svg = open(path, encoding="utf-8").read()
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    return re.sub(r"></path>", "/>", m.group(1).strip())


def main():
    remix = package("remixicon", REMIX_VERSION)
    index = {}
    for dirpath, _, files in os.walk(os.path.join(remix, "icons")):
        for f in files:
            index[f[:-4]] = os.path.join(dirpath, f)
    lines = [
        f"// Code generated by scripts/gen-glyphs.py from Remix Icon {REMIX_VERSION}",
        "// (https://remixicon.com). DO NOT EDIT.",
        "",
        "package view",
        "",
        "var (",
    ]
    width = max(len(k) for k in REMIX)
    for go, name in sorted(REMIX.items(), key=lambda kv: kv[0].lower()):
        body = remix_body(index[name]).replace("`", "")
        lines.append(f"\t{go.ljust(width)} = remix(`{body}`) // {name}")
    lines += [")", ""]
    gen = os.path.join(ROOT, "internal/view/glyphs_gen.go")
    with open(gen, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    subprocess.run(["gofmt", "-w", gen], check=True)

    lobe = package("@lobehub/icons-static-svg", LOBE_VERSION)
    out = os.path.join(ROOT, "internal/view/assets/providers")
    os.makedirs(out, exist_ok=True)
    for name in os.listdir(out):
        if name.endswith(".svg"):
            os.remove(os.path.join(out, name))
    for name in LOBE:
        svg = open(os.path.join(lobe, "icons", name + ".svg"), encoding="utf-8").read()
        # The size is the viewBox's; the rest is for the web.
        svg = re.sub(r'\s(height|width|style)="[^"]*"', "", svg, count=3)
        svg = re.sub(r"<title>.*?</title>", "", svg)
        with open(os.path.join(out, name + ".svg"), "w", encoding="utf-8") as f:
            f.write(svg)
    print(json.dumps({"glyphs": len(REMIX), "providers": len(LOBE)}))


if __name__ == "__main__":
    main()
